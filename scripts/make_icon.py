"""Builds Hramota's launcher icon (adaptive: background, foreground, monochrome) from the design.

The design was measured pixel by pixel on the reference picture (a 435 px circle); every shape is
given here in those pixels and converted to the 108 dp adaptive-icon grid, where the circle a
launcher shows is 72 dp across. Run: python3 scripts/make_icon.py
"""
import os

RES = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res")
CX, CY, R = 350.0, 289.5, 220.0          # the reference circle, in its pixels
S = 36.0 / R                              # pixels to dp: the circle is 72 dp across


def x(v): return 54 + (v - CX) * S
def y(v): return 54 + (v - CY) * S
def d(v): return v * S
def f(v): return f"{v:.2f}".rstrip("0").rstrip(".")


def P(*parts):
    """Path text from ("M", x, y) / ("H", x) / ("V", y) / ("A", r, sweep, x, y) / ("L", x, y) / ("Z",) in reference pixels."""
    out = []
    for p in parts:
        k = p[0]
        if k in ("M", "L"): out.append(f"{k}{f(x(p[1]))},{f(y(p[2]))}")
        elif k == "H": out.append(f"H{f(x(p[1]))}")
        elif k == "V": out.append(f"V{f(y(p[1]))}")
        elif k == "A": out.append(f"A{f(d(p[1]))},{f(d(p[1]))} 0 0 {p[2]} {f(x(p[3]))},{f(y(p[4]))}")
        elif k == "Z": out.append("Z")
    return " ".join(out)


# The front page: rounded corners (14), the folded corner cut out with a rounded inner corner (16)
FRONT = P(("M", 296, 150), ("H", 406), ("V", 213.5), ("A", 16, 0, 422, 229.5), ("H", 488), ("V", 388),
          ("A", 14, 1, 474, 402), ("H", 296), ("A", 14, 1, 282, 388), ("V", 164), ("A", 14, 1, 296, 150), ("Z",))
# The folded corner
FOLD = P(("M", 422.5, 157.5), ("L", 476.5, 211.5), ("H", 424.5), ("A", 2, 1, 422.5, 209.5), ("Z",))


def line(x0, x1, cy, h=6.5):
    return P(("M", x0, cy - h), ("H", x1), ("A", h, 1, x1, cy + h), ("H", x0), ("A", h, 1, x0, cy - h), ("Z",))


LINES = [line(321.5, 447.5, 263), line(321.5, 447.5, 306), line(321.5, 422.5, 348)]
# The page behind: only its left edge and bottom show, around the front page and the gap left round it
MIDDLE = P(("M", 265.5, 182), ("H", 253), ("A", 14, 0, 239, 196), ("V", 428.5), ("A", 14, 0, 253, 442.5), ("H", 414.5),
           ("A", 14, 0, 428.5, 428.5), ("V", 418.5), ("H", 296), ("A", 30.5, 1, 265.5, 388), ("V", 182), ("Z",))
# The last page: its left edge
BACK = P(("M", 224, 226), ("H", 216), ("A", 14, 0, 202, 240), ("V", 402), ("A", 14, 0, 216, 416), ("H", 224), ("Z",))

CREAM, YELLOW, INK = "#FFFAE7CE", "#FFFDB42D", "#FF012E61"
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n{comment}\n<vector xmlns:android="http://schemas.android.com/apk/res/android"{aapt}\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')


def path(data, color, even_odd=False, alpha=None):
    extra = ' android:fillType="evenOdd"' if even_odd else ""
    if alpha is not None: extra += f' android:fillAlpha="{alpha}"'
    return f'    <path android:fillColor="{color}"{extra} android:pathData="{data}" />\n'


def write(name, body, comment, aapt=False):
    ns = '\n    xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    with open(os.path.join(RES, "drawable", name), "w", encoding="utf-8") as o:
        o.write(HEAD.format(comment=comment, aapt=ns) + body + "</vector>\n")


fg = path(BACK, YELLOW) + path(MIDDLE, YELLOW) + path(FRONT, CREAM) + path(FOLD, CREAM) + "".join(path(l, INK) for l in LINES)
write("ic_launcher_foreground.xml", fg, "<!-- Грамота: a document in front of two yellow pages (generated by scripts/make_icon.py) -->")

# Themed icons: one colour; the text lines are cut out of the page (even-odd), never drawn over it
mono = path(BACK, "#FF000000", alpha="0.6") + path(MIDDLE, "#FF000000", alpha="0.6") + \
    path(FRONT + " " + " ".join(LINES), "#FF000000", even_odd=True) + path(FOLD, "#FF000000")
write("ic_launcher_monochrome.xml", mono, "<!-- Themed (one-colour) icon: pages as shapes, the text lines cut out (generated by scripts/make_icon.py) -->")

# Background: the deep blue of the design, lighter at the top left
bg = ('    <path android:pathData="M0,0 H108 V108 H0 Z">\n        <aapt:attr name="android:fillColor">\n'
      f'            <gradient android:type="linear" android:startX="{f(x(250))}" android:startY="{f(y(100))}" android:endX="{f(x(470))}" android:endY="{f(y(480))}">\n'
      '                <item android:offset="0" android:color="#FF0C3A6B" />\n                <item android:offset="1" android:color="#FF002D60" />\n'
      '            </gradient>\n        </aapt:attr>\n    </path>\n')
write("ic_launcher_background.xml", bg, "<!-- The icon's background (generated by scripts/make_icon.py) -->", aapt=True)

# The same shapes as SVG, for comparing with the design
svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="435" height="435"><defs>'
       f'<linearGradient id="g" gradientUnits="userSpaceOnUse" x1="{f(x(250))}" y1="{f(y(100))}" x2="{f(x(470))}" y2="{f(y(480))}"><stop offset="0" stop-color="#0C3A6B"/><stop offset="1" stop-color="#002D60"/></linearGradient>'
       '<clipPath id="c"><circle cx="54" cy="54" r="36"/></clipPath></defs><rect x="0" y="0" width="108" height="108" fill="#141019"/><g clip-path="url(#c)">'
       '<rect width="108" height="108" fill="url(#g)"/>']
for data, color in [(BACK, "#FDB42D"), (MIDDLE, "#FDB42D"), (FRONT, "#FAE7CE"), (FOLD, "#FAE7CE")] + [(l, "#012E61") for l in LINES]:
    svg.append(f'<path fill="{color}" d="{data}"/>')
svg.append("</g></svg>")
os.makedirs("build", exist_ok=True)
open("build/icon-check.svg", "w").write("".join(svg))
print("written")
